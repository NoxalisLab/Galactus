// ---------------------------------------------------------------- resolution

/// Bundle Resources dir (packaged app), the src-tauri dir (dev run), or the
/// crate dir (cargo test). A deliberate twin of lib.rs::resource_dir and of
/// pylang.rs's copy, for the same reason those two are twins: this module must
/// resolve its own tooling without reaching into the app.
fn resource_dir() -> Option<PathBuf> {
    let has = |p: &PathBuf| p.join("rust-tooling").exists();
    if let Ok(exe) = std::env::current_exe() {
        if let Some(res) = exe.parent().and_then(|p| p.parent()).map(|p| p.join("Resources")) {
            if has(&res) {
                return Some(res);
            }
        }
    }
    let cwd = std::env::current_dir().unwrap_or_default();
    if has(&cwd) {
        return Some(cwd);
    }
    let dev = cwd.join("src-tauri");
    if has(&dev) {
        return Some(dev);
    }
    #[cfg(debug_assertions)]
    {
        let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
        if has(&manifest) {
            return Some(manifest);
        }
    }
    None
}

/// The bundled server and the bundled `library/` directory of std sources.
/// `GALACTUS_RUST_ANALYZER` and `GALACTUS_RUST_SRC` override both, which is how
/// a test points at a checkout copy.
pub fn tooling() -> Option<(PathBuf, PathBuf)> {
    let env_bin = std::env::var("GALACTUS_RUST_ANALYZER").ok().filter(|s| !s.is_empty());
    let env_src = std::env::var("GALACTUS_RUST_SRC").ok().filter(|s| !s.is_empty());
    if let (Some(b), Some(s)) = (&env_bin, &env_src) {
        let (b, s) = (PathBuf::from(b), PathBuf::from(s));
        if b.is_file() && s.is_dir() {
            return Some((b, s));
        }
    }
    let root = resource_dir()?.join("rust-tooling");
    let bin = root.join("rust-analyzer");
    let src = root.join("rust-src/library");
    if bin.is_file() && src.is_dir() {
        ensure_executable(&bin);
        Some((bin, src))
    } else {
        None
    }
}

fn ensure_executable(p: &Path) {
    // Resource copying does not preserve the executable bit, exactly as
    // lib.rs::bundled_engine documents for llama-server.
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        if let Ok(meta) = std::fs::metadata(p) {
            let mut perm = meta.permissions();
            if perm.mode() & 0o111 == 0 {
                perm.set_mode(0o755);
                let _ = std::fs::set_permissions(p, perm);
            }
        }
    }
    let _ = p;
}

/// The sysroot a real rustc reports, when this machine has one.
///
/// Asking rustc beats rust-analyzer's own `"discover"`: discovery runs the
/// rustup shim through PATH, and this app resolves tools with toolchain.rs
/// precisely so that a PATH lookup never decides what gets spawned. Without a
/// rustc the answer is None and the server runs on the bundled sources alone,
/// which is enough for `std::` and not enough for the project's dependencies.
fn discover_sysroot() -> Option<PathBuf> {
    let rustc = crate::toolchain::resolve("rustc")?;
    let out = Command::new(rustc)
        .arg("--print")
        .arg("sysroot")
        .stdin(Stdio::null())
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    let p = PathBuf::from(String::from_utf8_lossy(&out.stdout).trim().to_string());
    if p.is_dir() {
        Some(p)
    } else {
        None
    }
}

// ---------------------------------------------------------------- state

/// Where unsolicited traffic goes. A closure rather than an `AppHandle` so the
/// session can be driven from a test with no Tauri app and no window.
pub type Sink = Box<dyn Fn(Value) + Send + Sync>;

struct Session {
    child: Child,
    stdin: ChildStdin,
    root: PathBuf,
    root_uri: String,
    server: String,
    sysroot: Option<String>,
    sysroot_src: String,
    cargo: bool,
}

fn session() -> &'static Mutex<Option<Session>> {
    static S: OnceLock<Mutex<Option<Session>>> = OnceLock::new();
    S.get_or_init(|| Mutex::new(None))
}

/// Serialises `start` and `stop` end to end.
///
/// The session mutex alone is NOT enough, and the gap is a process leak.
/// `start` clears the session, spawns, then assigns, releasing the session
/// lock between each step. Two concurrent starts can therefore both find
/// nothing running, both spawn, and the second assignment DROPS the first
/// `Session`. `std::process::Child` has no `Drop` that kills, so that first
/// rust-analyzer keeps running, is no longer reachable through `session()`,
/// and neither `stop()` nor `shutdown_all()` on the exit path can ever reap
/// it: a whole crate index left in RAM after the app has quit.
///
/// Two concurrent starts are reachable from the app: `enableRustLsp` is async
/// and two callers can both get past their teardown before either spawns.
fn lifecycle_lock() -> &'static Mutex<()> {
    static L: OnceLock<Mutex<()>> = OnceLock::new();
    L.get_or_init(|| Mutex::new(()))
}

type Pending = HashMap<i64, Sender<Result<Value, String>>>;

fn pending() -> &'static Mutex<Pending> {
    static P: OnceLock<Mutex<Pending>> = OnceLock::new();
    P.get_or_init(|| Mutex::new(HashMap::new()))
}

/// Ids are unique for the life of the process, not per session, so a late
/// answer from a killed server can never be matched to a new request.
static NEXT_ID: AtomicI64 = AtomicI64::new(1);

/// Bumped on every start and every stop. The reader thread carries its own
/// copy and stops touching shared state as soon as it no longer matches, which
/// is what keeps a dying server from tearing down the one that replaced it.
static GENERATION: AtomicU64 = AtomicU64::new(0);

/// Last words of a dead server, for the error message.
fn stderr_tail() -> &'static Mutex<String> {
    static E: OnceLock<Mutex<String>> = OnceLock::new();
    E.get_or_init(|| Mutex::new(String::new()))
}

#[derive(Serialize, Clone, Debug, Default)]
pub struct LspStatus {
    pub running: bool,
    pub root: Option<String>,
    pub root_uri: Option<String>,
    /// The server's own version string, as `rust-analyzer --version` prints it.
    pub server: Option<String>,
    pub sysroot: Option<String>,
    pub sysroot_src: Option<String>,
    /// A real cargo was found. Without one the crate graph of the user's own
    /// dependencies cannot be built, and the UI must not promise otherwise.
    pub cargo: bool,
    pub pid: Option<u32>,
    /// Non-fatal limitation, in plain words, for the badge tooltip.
    pub note: Option<String>,
}

pub fn status() -> LspStatus {
    let guard = session().lock().unwrap_or_else(|e| e.into_inner());
    match guard.as_ref() {
        None => LspStatus::default(),
        Some(s) => LspStatus {
            running: true,
            root: Some(s.root.display().to_string()),
            root_uri: Some(s.root_uri.clone()),
            server: Some(s.server.clone()),
            sysroot: s.sysroot.clone(),
            sysroot_src: Some(s.sysroot_src.clone()),
            cargo: s.cargo,
            pid: Some(s.child.id()),
            note: note_for(s.cargo, s.sysroot.is_some()),
        },
    }
}

fn note_for(cargo: bool, sysroot: bool) -> Option<String> {
    if cargo {
        return None;
    }
    Some(
        if sysroot {
            "no cargo on this Mac: the standard library resolves, the project's own \
             dependencies do not"
        } else {
            "no Rust toolchain on this Mac: only the bundled standard library sources \
             resolve, and nothing from the project's dependencies"
        }
        .to_string(),
    )
}

// ---------------------------------------------------------------- transport

/// Serialise one JSON value onto the pipe. Holds the session lock for the
/// duration of the write and nothing more: a caller that waits for an answer
/// must do it after this returns, or two requests deadlock each other.
fn write_message(value: &Value) -> Result<(), String> {
    let text = serde_json::to_string(value).map_err(|e| e.to_string())?;
    let mut guard = session().lock().unwrap_or_else(|e| e.into_inner());
    let s = guard.as_mut().ok_or("the Rust language server is not running")?;
    s.stdin
        .write_all(&encode(&text))
        .and_then(|_| s.stdin.flush())
        .map_err(|e| format!("cannot write to the Rust language server: {e}"))
}

/// Post a request and hand back its id plus the channel the answer will arrive
/// on. The id comes back rather than being re-read from the counter: another
/// thread can allocate an id between the two reads, and cancelling somebody
/// else's request is a bug that only appears under two users of one server.
fn enqueue(method: &str, params: Value) -> Result<(i64, Receiver<Result<Value, String>>), String> {
    let id = NEXT_ID.fetch_add(1, Ordering::SeqCst);
    let (tx, rx) = channel();
    pending().lock().unwrap_or_else(|e| e.into_inner()).insert(id, tx);
    let message = json!({"jsonrpc": "2.0", "id": id, "method": method, "params": params});
    if let Err(e) = write_message(&message) {
        pending().lock().unwrap_or_else(|e| e.into_inner()).remove(&id);
        return Err(e);
    }
    Ok((id, rx))
}

/// A request, start to finish. `$/cancelRequest` is sent on expiry so the
/// server stops working on an answer nobody will read.
fn request(method: &str, params: Value, deadline: Duration) -> Result<Value, String> {
    let (id, rx) = enqueue(method, params)?;
    match rx.recv_timeout(deadline) {
        Ok(v) => v,
        Err(_) => {
            pending().lock().unwrap_or_else(|e| e.into_inner()).remove(&id);
            let _ = write_message(&json!({
                "jsonrpc": "2.0", "method": "$/cancelRequest", "params": {"id": id}
            }));
            Err(format!("{method} did not answer within {deadline:?}"))
        }
    }
}

fn notify(method: &str, params: Value) -> Result<(), String> {
    write_message(&json!({"jsonrpc": "2.0", "method": method, "params": params}))
}

/// Every waiting caller gets the same failure, once, when the server dies.
fn fail_pending(reason: &str) {
    let drained: Vec<Sender<Result<Value, String>>> = {
        let mut map = pending().lock().unwrap_or_else(|e| e.into_inner());
        map.drain().map(|(_, tx)| tx).collect()
    };
    for tx in drained {
        let _ = tx.send(Err(reason.to_string()));
    }
}

// ---------------------------------------------------------------- reader

/// The one thread that reads the server's stdout.
///
/// Three kinds of traffic arrive here and all three must be handled, which is
/// the part a naive client gets wrong:
///   * responses, matched to a waiting caller by id;
///   * notifications, forwarded to the frontend (diagnostics and progress);
///   * REQUESTS FROM THE SERVER. rust-analyzer asks the client to create a
///     progress token before it starts indexing and blocks its own startup
///     until the answer comes back. An unknown server request gets a proper
///     JSON-RPC MethodNotFound error rather than silence, because silence is
///     what makes the server sit there forever looking like a hang.
fn reader_loop(mut stdout: std::process::ChildStdout, generation: u64, sink: Sink) {
    let mut decoder = FrameDecoder::new();
    let mut chunk = [0u8; 16 * 1024];
    let ended: String = loop {
        let n = match stdout.read(&mut chunk) {
            Ok(0) => break "the Rust language server closed its output".to_string(),
            Ok(n) => n,
            Err(e) => break format!("cannot read from the Rust language server: {e}"),
        };
        decoder.push(&chunk[..n]);
        loop {
            match decoder.next_message() {
                Ok(None) => break,
                Ok(Some(text)) => dispatch(&text, &sink),
                // Unparseable framing: the stream cannot be resynchronised, so
                // the session is over. Reporting it beats decoding noise.
                Err(e) => {
                    finish(generation, &format!("the Rust language server sent {e}"), &sink);
                    return;
                }
            }
        }
    };
    finish(generation, &ended, &sink);
}

fn dispatch(text: &str, sink: &Sink) {
    let value: Value = match serde_json::from_str(text) {
        Ok(v) => v,
        // One bad message is survivable; framing was intact, so the next one
        // still starts where it should.
        Err(_) => return,
    };
    let has_id = value.get("id").map(|v| !v.is_null()).unwrap_or(false);
    let method = value.get("method").and_then(|m| m.as_str()).map(str::to_string);

    match (has_id, method) {
        // Response to something we asked.
        (true, None) => {
            let id = match value.get("id").and_then(Value::as_i64) {
                Some(i) => i,
                None => return,
            };
            let tx = pending().lock().unwrap_or_else(|e| e.into_inner()).remove(&id);
            if let Some(tx) = tx {
                let answer = if let Some(err) = value.get("error") {
                    Err(lsp_error_message(err))
                } else {
                    Ok(value.get("result").cloned().unwrap_or(Value::Null))
                };
                let _ = tx.send(answer);
            }
        }
        // Request FROM the server.
        (true, Some(m)) => {
            let id = value.get("id").cloned().unwrap_or(Value::Null);
            let reply = match m.as_str() {
                // Accepting the token is what lets us report indexing progress.
                "window/workDoneProgress/create" | "client/registerCapability"
                | "client/unregisterCapability" => {
                    json!({"jsonrpc": "2.0", "id": id, "result": Value::Null})
                }
                _ => json!({
                    "jsonrpc": "2.0", "id": id,
                    "error": {"code": -32601, "message": format!("{m} is not supported by this client")}
                }),
            };
            let _ = write_message(&reply);
        }
        // Notification.
        (false, Some(m)) => {
            let params = value.get("params").cloned().unwrap_or(Value::Null);
            match m.as_str() {
                "textDocument/publishDiagnostics" => {
                    sink(json!({"kind": "diagnostics", "params": params}))
                }
                "$/progress" => sink(json!({"kind": "progress", "params": params})),
                "window/logMessage" | "window/showMessage" => {
                    sink(json!({"kind": "log", "params": params}))
                }
                _ => {}
            }
        }
        (false, None) => {}
    }
}

fn lsp_error_message(err: &Value) -> String {
    let message = err.get("message").and_then(Value::as_str).unwrap_or("unknown error");
    match err.get("code").and_then(Value::as_i64) {
        Some(code) => format!("{message} (LSP error {code})"),
        None => message.to_string(),
    }
}

/// The session is over: unblock every waiter and tell the frontend, but only
/// if this reader still owns the current generation. A restart that overlapped
/// with a dying server must not have its state torn down by the corpse.
fn finish(generation: u64, reason: &str, sink: &Sink) {
    if GENERATION.load(Ordering::SeqCst) != generation {
        return;
    }
    let tail = stderr_tail().lock().unwrap_or_else(|e| e.into_inner()).clone();
    let detail = last_lines(&tail, 3);
    let full = if detail.is_empty() {
        reason.to_string()
    } else {
        format!("{reason}: {detail}")
    };
    {
        let mut guard = session().lock().unwrap_or_else(|e| e.into_inner());
        if let Some(mut s) = guard.take() {
            let _ = s.child.kill();
            let _ = s.child.wait();
        }
    }
    fail_pending(&full);
    sink(json!({"kind": "stopped", "reason": full}));
}

fn last_lines(s: &str, n: usize) -> String {
    let lines: Vec<&str> = s.lines().filter(|l| !l.trim().is_empty()).collect();
    lines[lines.len().saturating_sub(n)..].join(" / ")
}


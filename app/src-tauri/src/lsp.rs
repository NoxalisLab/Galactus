/// Start a server for one workspace root. Blocking: call it off the UI thread.
///
/// Idempotent in the only way that matters: an existing session is stopped
/// first, so a second call cannot leave an orphan holding a gigabyte of index.
pub fn start(root: &Path, sink: Sink) -> Result<LspStatus, String> {
    if !root.is_dir() {
        return Err(format!("{} is not a folder", root.display()));
    }
    let (bin, src) = tooling().ok_or(NO_SERVER)?;
    // Held for the whole function, see lifecycle_lock. `stop_locked` and not
    // `stop`, because the lock is not reentrant and `stop` takes it too.
    let _serialised = lifecycle_lock().lock().unwrap_or_else(|e| e.into_inner());
    stop_locked();

    let generation = GENERATION.fetch_add(1, Ordering::SeqCst) + 1;
    let version = server_version(&bin);
    let sysroot = discover_sysroot();
    let cargo = crate::toolchain::resolve("cargo").is_some();

    let mut child = Command::new(&bin)
        .current_dir(root)
        // rust-analyzer picks up RA_LOG and friends; an inherited value from a
        // developer shell would turn stderr into a firehose inside the app.
        .env_remove("RA_LOG")
        .env_remove("RUST_LOG")
        .env_remove("RA_PROFILE")
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|e| format!("cannot start the bundled rust-analyzer ({}): {e}", bin.display()))?;

    let stdin = child.stdin.take().ok_or("no stdin pipe")?;
    let stdout = child.stdout.take().ok_or("no stdout pipe")?;
    let stderr = child.stderr.take().ok_or("no stderr pipe")?;
    stderr_tail().lock().unwrap_or_else(|e| e.into_inner()).clear();

    let root_uri = path_to_uri(root);
    *session().lock().unwrap_or_else(|e| e.into_inner()) = Some(Session {
        child,
        stdin,
        root: root.to_path_buf(),
        root_uri: root_uri.clone(),
        server: version.clone(),
        sysroot: sysroot.as_ref().map(|p| p.display().to_string()),
        sysroot_src: src.display().to_string(),
        cargo,
    });

    // stderr is drained on its own thread and kept bounded: an undrained pipe
    // fills, and a server blocked writing a log line looks exactly like a hang.
    std::thread::spawn(move || {
        let mut reader = stderr;
        let mut chunk = [0u8; 4096];
        while let Ok(n) = reader.read(&mut chunk) {
            if n == 0 {
                break;
            }
            let mut tail = stderr_tail().lock().unwrap_or_else(|e| e.into_inner());
            tail.push_str(&String::from_utf8_lossy(&chunk[..n]));
            if tail.len() > STDERR_TAIL_BYTES {
                let cut = tail.len() - STDERR_TAIL_BYTES;
                *tail = tail[cut..].to_string();
            }
        }
    });

    std::thread::spawn(move || reader_loop(stdout, generation, sink));

    let params = initialize_params(root, &root_uri, &src, sysroot.as_deref());
    let result = match request("initialize", params, INIT_DEADLINE) {
        Ok(v) => v,
        Err(e) => {
            // A server that cannot initialize is not a server. Take it down
            // rather than leave a process that answers later requests with junk.
            stop();
            return Err(e);
        }
    };
    check_position_encoding(&result)?;
    notify("initialized", json!({}))?;

    Ok(status())
}

/// The version line, for the badge tooltip. Cheap and worth having: a stale
/// bundle is otherwise indistinguishable from a fresh one.
fn server_version(bin: &Path) -> String {
    Command::new(bin)
        .arg("--version")
        .stdin(Stdio::null())
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| "rust-analyzer (version unknown)".to_string())
}

/// We offer utf-16 and nothing else, so the server has to answer utf-16.
///
/// This is the single most expensive mistake available in an LSP client. A
/// JavaScript string is UTF-16 code units, so utf-16 positions map to editor
/// offsets with no conversion at all; accept utf-8 by accident and every line
/// containing an accent, an emoji or a box-drawing character reports its
/// columns a few units off, which shows up as a hover on the wrong token and
/// a rename that eats a neighbouring character.
fn check_position_encoding(init_result: &Value) -> Result<(), String> {
    let encoding = init_result
        .get("capabilities")
        .and_then(|c| c.get("positionEncoding"))
        .and_then(Value::as_str)
        // Absent means the pre-3.17 default, which is utf-16.
        .unwrap_or("utf-16");
    if encoding == "utf-16" {
        Ok(())
    } else {
        stop();
        Err(format!(
            "the Rust language server insists on {encoding} positions, which this editor \
             cannot map safely"
        ))
    }
}

fn initialize_params(root: &Path, root_uri: &str, sysroot_src: &Path, sysroot: Option<&Path>) -> Value {
    json!({
        "processId": std::process::id(),
        "rootUri": root_uri,
        "rootPath": root.display().to_string(),
        "workspaceFolders": [{
            "uri": root_uri,
            "name": root.file_name().map(|n| n.to_string_lossy().to_string()).unwrap_or_default(),
        }],
        "clientInfo": {"name": "Galactus"},
        "capabilities": {
            "general": {"positionEncodings": ["utf-16"]},
            "window": {
                // True so the server creates a progress token and we can tell
                // the user that answers are incomplete while it indexes.
                "workDoneProgress": true,
                "showMessage": {"messageActionItem": {"additionalPropertiesSupport": false}}
            },
            "workspace": {
                // Both false so the server never asks us a question we would
                // have to answer well: it reads initializationOptions instead.
                "configuration": false,
                "workspaceFolders": false,
                "applyEdit": false,
                "symbol": {"dynamicRegistration": false}
            },
            "textDocument": {
                "synchronization": {
                    "dynamicRegistration": false,
                    "didSave": false,
                    "willSave": false
                },
                "publishDiagnostics": {"relatedInformation": true, "versionSupport": true},
                "hover": {"contentFormat": ["markdown", "plaintext"]},
                "definition": {"linkSupport": false},
                "references": {"dynamicRegistration": false},
                "documentSymbol": {"hierarchicalDocumentSymbolSupport": true},
                "completion": {
                    "completionItem": {
                        "snippetSupport": false,
                        "documentationFormat": ["plaintext", "markdown"],
                        "resolveSupport": {"properties": ["documentation", "detail"]}
                    },
                    "contextSupport": true
                },
                "rename": {"prepareSupport": true},
                "signatureHelp": {
                    "signatureInformation": {"documentationFormat": ["plaintext"]}
                }
            }
        },
        "initializationOptions": {
            "cargo": {
                // A path, or null. Never "discover": see discover_sysroot.
                "sysroot": sysroot.map(|p| Value::from(p.display().to_string())).unwrap_or(Value::Null),
                // The bundled sources. Set even when a sysroot was found, so a
                // toolchain installed without the rust-src component still
                // resolves std instead of underlining every use of it.
                "sysrootSrc": sysroot_src.display().to_string(),
                "buildScripts": {"enable": false}
                // `cargo.autoreload: false` used to be here and MUST NOT come
                // back. Measured against rust-analyzer 0.3.2997 by bisecting
                // the init options one key at a time: with it set, the crate
                // graph never finishes loading, every hover answers null
                // forever and the server reports no error at all, so it looks
                // exactly like an indexing pass that never ends. Everything
                // else in this block was cleared the same way.
            },
            // Both of these execute code that came with the repository.
            "procMacro": {"enable": false},
            "checkOnSave": false,
            // Measured on this repo: priming walks all 256 crates of the
            // dependency graph and burns minutes of CPU before answering
            // anything. Hover and go to definition work perfectly without it,
            // computed on demand, so the whole cost buys a slightly faster
            // second request in exchange for a fan that never stops.
            "cachePriming": {"enable": false},
            "files": {
                "excludeDirs": ["target", "node_modules", ".git", "dist", "build", ".venv"]
            },
            "diagnostics": {"enable": true, "experimental": {"enable": false}},
            "hover": {"documentation": {"keywords": {"enable": false}}}
        }
    })
}

/// Stop the server. Graceful first (`shutdown` then `exit`, which is what lets
/// rust-analyzer flush its on-disk cache), then a kill, always.
///
/// Never fails and never blocks for long: it runs on the app's exit path, and
/// an exit path that can hang is a bug report about a beachball.
pub fn stop() {
    let _serialised = lifecycle_lock().lock().unwrap_or_else(|e| e.into_inner());
    stop_locked();
}

/// The body of `stop`, for callers that already hold `lifecycle_lock`.
fn stop_locked() {
    let running = session().lock().unwrap_or_else(|e| e.into_inner()).is_some();
    if !running {
        return;
    }
    // Retire the generation first: the reader thread is about to see EOF and
    // must not report that as a crash the user needs to know about.
    GENERATION.fetch_add(1, Ordering::SeqCst);

    if let Ok((_, rx)) = enqueue("shutdown", Value::Null) {
        let _ = rx.recv_timeout(Duration::from_secs(3));
    }
    let _ = notify("exit", Value::Null);

    // Take the session OUT of the mutex before waiting on the process. The
    // reader thread answers server requests, which needs this same lock, and
    // holding it across a two second wait would be a two second stall on the
    // exit path for no benefit.
    let taken = session().lock().unwrap_or_else(|e| e.into_inner()).take();
    if let Some(mut s) = taken {
        // Dropping stdin closes the pipe, which is a second, independent reason
        // for the server to exit: rust-analyzer stops on EOF.
        drop(s.stdin);
        let deadline = Instant::now() + Duration::from_secs(2);
        loop {
            match s.child.try_wait() {
                Ok(Some(_)) => break,
                Ok(None) if Instant::now() < deadline => {
                    std::thread::sleep(Duration::from_millis(20))
                }
                _ => {
                    let _ = s.child.kill();
                    let _ = s.child.wait();
                    break;
                }
            }
        }
    }
    fail_pending("the Rust language server was stopped");
}

/// Called from the app's Exit handler. An abandoned rust-analyzer keeps a
/// whole crate index in RAM and, unlike a window, nothing on screen says so.
pub fn shutdown_all() {
    stop();
}


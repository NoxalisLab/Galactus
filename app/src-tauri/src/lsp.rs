/// Start the server for `root`. Async so Tauri keeps it off the UI thread; the
/// work runs on the blocking pool because it waits on a child process.
#[tauri::command]
pub async fn rust_lsp_start(app: tauri::AppHandle, root: String) -> Result<LspStatus, String> {
    tauri::async_runtime::spawn_blocking(move || {
        let sink: Sink = Box::new(move |payload: Value| {
            use tauri::Emitter;
            let _ = app.emit(EVENT, payload);
        });
        start(Path::new(&root), sink)
    })
    .await
    .map_err(|e| format!("the Rust language server thread died: {e}"))?
}

#[tauri::command]
pub async fn rust_lsp_stop() -> Result<(), String> {
    tauri::async_runtime::spawn_blocking(stop)
        .await
        .map_err(|e| format!("the Rust language server thread died: {e}"))
}

/// Async and on the blocking pool like the rest, and for the reason spelled
/// out on `rust_lsp_notify` below: a Tauri command declared `fn` runs on the
/// MAIN thread, and `status()` takes the session mutex, which `write_message`
/// holds across a blocking `write_all` of a whole buffer. A synchronous
/// version therefore parks the webview's main thread for as long as a
/// multi-megabyte `didChange` takes to drain, which is precisely when the
/// server is busy and slow to read.
#[tauri::command]
pub async fn rust_lsp_status() -> Result<LspStatus, String> {
    tauri::async_runtime::spawn_blocking(status)
        .await
        .map_err(|e| format!("the Rust language server thread died: {e}"))
}

/// Issue one request. Refused outright when the method is not on the read-only
/// allowlist, so the frontend cannot be talked into asking the server to build.
#[tauri::command]
pub async fn rust_lsp_request(
    method: String,
    params: Value,
    timeout_ms: Option<u64>,
) -> Result<Value, String> {
    if !request_allowed(&method) {
        return Err(format!("{method} is not allowed: this client is read-only"));
    }
    let deadline = timeout_ms
        .map(Duration::from_millis)
        .unwrap_or(DEFAULT_REQUEST_DEADLINE);
    tauri::async_runtime::spawn_blocking(move || request(&method, params, deadline))
        .await
        .map_err(|e| format!("the Rust language server thread died: {e}"))?
}

/// Send one notification. Same allowlist rule.
///
/// Async like the rest, even though there is no answer to wait for: a Tauri
/// command declared `fn` runs on the MAIN thread, and `didChange` carries the
/// whole buffer. A pipe write blocks once the kernel buffer is full, so a
/// synchronous version would freeze the window whenever the server stopped
/// draining, which is exactly when it is busy indexing.
#[tauri::command]
pub async fn rust_lsp_notify(method: String, params: Value) -> Result<(), String> {
    if !notification_allowed(&method) {
        return Err(format!("{method} is not allowed: this client is read-only"));
    }
    tauri::async_runtime::spawn_blocking(move || notify(&method, params))
        .await
        .map_err(|e| format!("the Rust language server thread died: {e}"))?
}


/// Event name the frontend listens on. One channel for every kind of
/// unsolicited traffic, discriminated by `kind`, so the frontend registers a
/// single listener and cannot miss a message by forgetting a name.
pub const EVENT: &str = "galactus://rust-lsp";

/// How long `initialize` may take. rust-analyzer answers `initialize` before it
/// has indexed anything, so this is a startup budget, not an indexing budget:
/// thirty seconds means the process is wedged, not that the project is big.
pub const INIT_DEADLINE: Duration = Duration::from_secs(30);

/// Default budget for one request. Hover on a cold cache can genuinely take
/// seconds while the crate graph is still being built.
pub const DEFAULT_REQUEST_DEADLINE: Duration = Duration::from_secs(20);

/// A header block bigger than this is not a header block. Bounded so a server
/// that starts emitting garbage cannot grow our buffer without limit.
const MAX_HEADER_BYTES: usize = 8 * 1024;

/// Refuse absurd Content-Length values before allocating for them.
const MAX_MESSAGE_BYTES: usize = 64 * 1024 * 1024;

/// How much of the server's stderr to keep for the error message.
const STDERR_TAIL_BYTES: usize = 8 * 1024;

/// Shown when the bundle carries no server. Fail closed and say why: the user
/// can act on "reinstall", not on a silent absence of hovers.
pub const NO_SERVER: &str =
    "rust-analyzer is not in this build of Galactus: .rs files keep syntax highlighting, \
     outline and syntax errors, but no types, no hover and no go to definition";

// ---------------------------------------------------------------- framing

/// Incremental decoder for the LSP wire format: `Content-Length: N\r\n\r\n`
/// followed by N bytes of UTF-8 JSON.
///
/// Incremental because a pipe read returns whatever happened to be in the
/// buffer: the header can arrive split down the middle of `Content-Length`,
/// and a 200 kB hover response arrives as a dozen chunks. Feeding a
/// `BufReader::read_line` loop looks simpler and is, right up to the day a
/// server writes a bare `\n` inside a JSON string and the line reader cuts the
/// body in half.
#[derive(Default)]
pub struct FrameDecoder {
    buf: Vec<u8>,
    /// Body length once the header has been consumed.
    need: Option<usize>,
}

impl FrameDecoder {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn push(&mut self, bytes: &[u8]) {
        self.buf.extend_from_slice(bytes);
    }

    /// Pull the next complete message, if there is one.
    ///
    /// `Ok(None)` means "not yet, feed me more". `Err` means the stream is not
    /// LSP any more and the caller must stop reading it: once a header is
    /// unparseable there is no way to find where the next one starts, and
    /// guessing produces a decoder that silently drops half the traffic.
    pub fn next_message(&mut self) -> Result<Option<String>, String> {
        if self.need.is_none() {
            let end = match find(&self.buf, b"\r\n\r\n") {
                Some(i) => i,
                None => {
                    if self.buf.len() > MAX_HEADER_BYTES {
                        return Err(format!(
                            "no LSP header in the first {MAX_HEADER_BYTES} bytes"
                        ));
                    }
                    return Ok(None);
                }
            };
            let header = String::from_utf8_lossy(&self.buf[..end]).into_owned();
            let len = parse_content_length(&header)?;
            if len > MAX_MESSAGE_BYTES {
                return Err(format!("message announces {len} bytes, over the limit"));
            }
            self.buf.drain(..end + 4);
            self.need = Some(len);
        }
        let want = self.need.expect("set just above");
        if self.buf.len() < want {
            return Ok(None);
        }
        let body: Vec<u8> = self.buf.drain(..want).collect();
        self.need = None;
        String::from_utf8(body).map(Some).map_err(|e| format!("message is not UTF-8: {e}"))
    }
}

fn find(haystack: &[u8], needle: &[u8]) -> Option<usize> {
    if needle.is_empty() || haystack.len() < needle.len() {
        return None;
    }
    haystack.windows(needle.len()).position(|w| w == needle)
}

/// Read Content-Length out of a header block. Unknown fields are ignored, as
/// the specification requires; a missing or unparseable length is fatal.
fn parse_content_length(header: &str) -> Result<usize, String> {
    let mut found: Option<usize> = None;
    for line in header.split("\r\n") {
        if line.is_empty() {
            continue;
        }
        let (name, value) = match line.split_once(':') {
            Some(p) => p,
            None => return Err(format!("malformed LSP header line: {line:?}")),
        };
        if !name.trim().eq_ignore_ascii_case("content-length") {
            continue;
        }
        found = Some(
            value
                .trim()
                .parse::<usize>()
                .map_err(|_| format!("bad Content-Length: {:?}", value.trim()))?,
        );
    }
    found.ok_or_else(|| "LSP header without Content-Length".to_string())
}

/// Frame one payload for the wire. No Content-Type: it is optional, and
/// rust-analyzer rejects the charset spelling some clients still send.
pub fn encode(payload: &str) -> Vec<u8> {
    let mut out = Vec::with_capacity(payload.len() + 32);
    out.extend_from_slice(format!("Content-Length: {}\r\n\r\n", payload.len()).as_bytes());
    out.extend_from_slice(payload.as_bytes());
    out
}

// ---------------------------------------------------------------- uri

/// Percent-encode one path segment byte by byte.
///
/// Deliberately conservative: everything outside the RFC 3986 unreserved set
/// is escaped, `/` excepted because it is the separator. A workspace under
/// `/Volumes/NoxalisExtended/Noxalis Lab/...` is the normal case on this
/// project, and a raw space in a URI makes rust-analyzer answer about a file
/// it never opened rather than fail loudly.
pub fn path_to_uri(path: &Path) -> String {
    let raw = path.to_string_lossy();
    let mut out = String::from("file://");
    for b in raw.as_bytes() {
        let c = *b as char;
        if c.is_ascii_alphanumeric() || matches!(c, '-' | '.' | '_' | '~' | '/') {
            out.push(c);
        } else {
            out.push_str(&format!("%{b:02X}"));
        }
    }
    out
}


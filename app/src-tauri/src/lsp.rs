// Galactus desktop, the bundled rust-analyzer driven over LSP.
//
// The app already ships rust-analyzer and the Rust standard library sources
// (see scripts/fetch-rust-tooling.sh). Until this module existed nothing drove
// them, so a .rs file got the Lezer grammar and 108 MB of the download was
// dead weight. This is the process side: spawn, frame, correlate, kill.
//
// THE SYSROOT, and why the fetch script pays for 70 MB of sources. A
// rust-analyzer with no sysroot resolves navigation inside the project but
// cannot resolve `std::` anything, and it does not degrade quietly: it reports
// unresolved-import errors on nearly every file. A server that underlines the
// whole buffer in red is strictly worse than no server, so `initialize` points
// `cargo.sysrootSrc` at the bundled `library/` and the sysroot itself at the
// path a real rustc reports, when this machine has one.
//
// WHAT THE SERVER IS NOT ALLOWED TO DO, decided here rather than at the call
// site. rust-analyzer is a build tool wearing a language server costume: build
// scripts, proc macros, `cargo check` on save and `workspace/executeCommand`
// all execute code that came out of the repository the user just opened. This
// app gates shell and file access behind an explicit permission prompt, so a
// language server must not become the way around it. Three defences, none of
// them optional:
//   * `buildScripts.enable` and `procMacro.enable` are false in the init
//     options, and `checkOnSave` is false, so opening a folder never compiles
//     anything. The cost is real (a crate whose API is generated by a build
//     script resolves worse) and it is the right trade for an offline app.
//   * `rust_lsp_request` accepts an ALLOWLIST of read-only methods. Anything
//     else is refused before it reaches the pipe, including the execute-command
//     family that runs cargo.
//   * nothing here writes a file. Rename produces a plan; the Code view turns
//     it into a proposal the user accepts hunk by hunk, like every other edit.
//
// Concurrency. One server at a time, under one mutex. Requests are correlated
// by JSON-RPC id through a pending map and answered on a channel, so the Tauri
// command can wait on the blocking pool without holding the lock and without
// touching the async runtime's threads. The reader is a plain OS thread parked
// in `read()`, which is what a pipe wants, and it is also the thread that
// answers the requests the SERVER sends US: leaving those unanswered is the
// classic way to make rust-analyzer wedge halfway through initialization.
//
// The framing codec and the URI encoder at the top are pure and are unit
// tested at the bottom of this file, because a header split across two reads
// is exactly the bug that only shows up on a slow machine.


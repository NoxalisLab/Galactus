    /// The real subprocess, end to end. Not part of the default run: it needs
    /// the bundled tooling, it spawns a process and it indexes a crate.
    ///
    ///   cargo test --lib -- --ignored --nocapture lsp::tests::live
    ///
    /// What it proves, in order of what would actually break in production:
    ///   1. the bundled binary starts, initializes and agrees on utf-16;
    ///   2. `std::` RESOLVES. A hover on `Duration` that comes back mentioning
    ///      core::time is the only evidence that the sysroot wiring works, and
    ///      it is the whole reason the bundle carries 70 MB of sources;
    ///   3. the file it just analysed reports NO unresolved-import errors. That
    ///      is the failure this feature exists to avoid: a server with no
    ///      sysroot underlines every use of std and is worse than no server;
    ///   4. stop() actually reaps the process.
    #[test]
    #[ignore = "spawns the bundled rust-analyzer against this crate"]
    fn live_server_resolves_std_and_reports_clean() {
        // GALACTUS_LSP_TEST_ROOT lets the same test drive a checkout other than
        // the crate it was compiled in.
        let root = std::env::var("GALACTUS_LSP_TEST_ROOT")
            .map(PathBuf::from)
            .unwrap_or_else(|_| PathBuf::from(env!("CARGO_MANIFEST_DIR")));
        let events = std::sync::Arc::new(Mutex::new(Vec::<Value>::new()));
        let seen = events.clone();
        let st = start(
            &root,
            Box::new(move |v| seen.lock().unwrap_or_else(|e| e.into_inner()).push(v)),
        )
        .expect("server must start");
        println!("server:     {:?}", st.server);
        println!("sysroot:    {:?}", st.sysroot);
        println!("sysrootSrc: {:?}", st.sysroot_src);
        println!("cargo: {}  note: {:?}", st.cargo, st.note);
        assert!(st.running);
        let pid = st.pid.expect("a running server has a pid");

        // Any file will do for the outline, but resolution only happens for a
        // file that is IN THE MODULE TREE: rust-analyzer refuses to analyse a
        // .rs nobody declared with `mod`, and a test pointed at an orphan file
        // reports a broken sysroot when the sysroot is fine.
        let file = root.join(
            std::env::var("GALACTUS_LSP_TEST_FILE").unwrap_or_else(|_| "src/pylang.rs".into()),
        );
        let text = std::fs::read_to_string(&file).unwrap();
        let uri = path_to_uri(&file);
        notify(
            "textDocument/didOpen",
            json!({"textDocument": {"uri": uri, "languageId": "rust", "version": 1, "text": text}}),
        )
        .unwrap();

        // The outline is answered from the syntax tree alone, so it comes back
        // before indexing and proves nothing about resolution. Asserted anyway
        // because it is the cheapest signal that the pipe works at all.
        let symbols = request(
            "textDocument/documentSymbol",
            json!({"textDocument": {"uri": uri}}),
            DEFAULT_REQUEST_DEADLINE,
        )
        .expect("documentSymbol must answer");
        let outline = symbols.as_array().map(|a| a.len()).unwrap_or(0);
        println!("documentSymbol: {outline} top level symbols");
        assert!(outline > 0);

        // Line of `use std::time::{Duration, Instant};`, hovering the D.
        let (line, character) = locate(&text, "use std::time::{Duration").expect("import line");
        let character = character + "use std::time::{".chars().count() as u64;

        // Generous: a cold run reads cargo metadata and scans a few hundred
        // dependency roots before anything resolves. Warm, this takes seconds.
        let started = Instant::now();
        let deadline = started + Duration::from_secs(900);
        let mut hover_text = String::new();
        while Instant::now() < deadline {
            let hover = request(
                "textDocument/hover",
                json!({"textDocument": {"uri": uri}, "position": {"line": line, "character": character}}),
                DEFAULT_REQUEST_DEADLINE,
            )
            .unwrap_or(Value::Null);
            hover_text = hover["contents"]["value"].as_str().unwrap_or("").to_string();
            if hover_text.contains("Duration") {
                break;
            }
            std::thread::sleep(Duration::from_millis(500));
        }
        println!("hover resolved after {:?}", started.elapsed());
        println!("hover on Duration:\n{}", hover_text.trim());
        for v in events.lock().unwrap_or_else(|e| e.into_inner()).iter() {
            if v["kind"] == json!("log") {
                println!("server log: {}", v["params"]["message"].as_str().unwrap_or(""));
            }
        }
        assert!(
            hover_text.contains("Duration"),
            "std did not resolve: the sysroot wiring is broken"
        );

        // Wait for a diagnostics publication about this exact file.
        let mut errors: Vec<String> = Vec::new();
        let mut published = 0usize;
        let deadline = Instant::now() + Duration::from_secs(300);
        while Instant::now() < deadline {
            {
                let log = events.lock().unwrap_or_else(|e| e.into_inner());
                let mine: Vec<&Value> = log
                    .iter()
                    .filter(|v| v["kind"] == json!("diagnostics") && v["params"]["uri"] == json!(uri))
                    .collect();
                published = mine.len();
                if let Some(last) = mine.last() {
                    errors = last["params"]["diagnostics"]
                        .as_array()
                        .map(|a| {
                            a.iter()
                                .filter(|d| d["severity"] == json!(1))
                                .map(|d| d["message"].as_str().unwrap_or("").to_string())
                                .collect()
                        })
                        .unwrap_or_default();
                    break;
                }
            }
            std::thread::sleep(Duration::from_millis(500));
        }
        println!("publishDiagnostics for this file: {published}, errors: {}", errors.len());
        for e in errors.iter().take(5) {
            println!("  error: {e}");
        }
        assert!(published > 0, "the server never published diagnostics for the open file");
        assert!(errors.is_empty(), "the server reported errors on a file that compiles");

        stop();
        assert!(!status().running);
        // The child must be gone, not merely forgotten.
        let alive = Command::new("kill")
            .args(["-0", &pid.to_string()])
            .output()
            .map(|o| o.status.success())
            .unwrap_or(false);
        println!("pid {pid} still alive after stop: {alive}");
        assert!(!alive, "stop() left rust-analyzer running");
    }

    /// Zero-based line and character of the first occurrence of `needle`.
    /// Characters are counted in utf-16 units, like the protocol.
    fn locate(text: &str, needle: &str) -> Option<(u64, u64)> {
        for (n, line) in text.lines().enumerate() {
            if let Some(byte) = line.find(needle) {
                let character = line[..byte].encode_utf16().count() as u64;
                return Some((n as u64, character));
            }
        }
        None
    }
